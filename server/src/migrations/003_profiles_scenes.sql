-- Sport profiles: configuration only. Each saved change is a new immutable version, so scenes
-- recorded with an older version keep rendering correctly.
create table sport_profiles (
  id text primary key,
  name text not null,
  sport text not null,
  current_version integer not null,
  archived_at text,
  created_by text references users (id) on delete set null,
  created_at text not null,
  updated_at text not null
);

create table sport_profile_versions (
  profile_id text not null references sport_profiles (id) on delete cascade,
  version integer not null,
  definition text not null check (json_valid(definition)),
  created_by text references users (id) on delete set null,
  created_at text not null,
  primary key (profile_id, version)
);

alter table sessions add column sport_profile_id text references sport_profiles (id);
alter table sessions add column team text;
alter table sessions add column athletes text not null default '[]' check (json_valid(athletes));

-- Small uploaded files such as diagram backgrounds, stored in the same bucket as the videos.
create table assets (
  id text primary key,
  storage_key text not null unique,
  content_type text not null,
  size_bytes integer not null,
  width integer not null,
  height integer not null,
  status text not null check (status in ('uploading', 'ready')),
  created_by text references users (id) on delete set null,
  created_at text not null
);

-- A marked moment in a video. Event type and profile version refer to the session's profile.
create table scenes (
  id text primary key,
  session_id text not null references sessions (id) on delete cascade,
  video_file_id text not null references video_files (id) on delete cascade,
  start_sec real not null check (start_sec >= 0),
  end_sec real not null check (end_sec > start_sec),
  event_type_key text,
  profile_id text references sport_profiles (id),
  profile_version integer,
  comment text,
  status text not null default 'unreviewed'
    check (status in ('unreviewed', 'reviewed', 'rejected', 'duplicate')),
  -- Generated by the client, so a retried request never creates a second scene.
  client_id text unique,
  created_by text references users (id) on delete set null,
  created_at text not null
);

create index scenes_video on scenes (video_file_id, start_sec);
create index scenes_session on scenes (session_id);
